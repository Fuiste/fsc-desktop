import { _electron as electron } from 'playwright';
import { mkdir, readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { makeFixture } from '../test/fixtures.mjs';

const root = path.resolve('.qa', `run-${Date.now()}`);
await mkdir(root, { recursive: true });
const exportsDir = path.join(root, 'exports');
const photo = await makeFixture(path.join(exportsDir, 'coast-sample.jpg'), { width: 4200, height: 2800 });
const wide = await makeFixture(path.join(exportsDir, 'panorama-sample.jpg'), { width: 2400, height: 800 });
const executablePath = process.env.FSC_EXECUTABLE;
const app = await electron.launch({ ...(executablePath ? { executablePath } : {}), args: executablePath ? [photo, wide] : ['.', photo, wide], timeout: 60000 });
const page = await app.firstWindow();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.locator('#preview').waitFor({ state: 'visible', timeout: 60000 });
  await page.locator('#loading').waitFor({ state: 'hidden', timeout: 60000 });
  assert.equal(await page.locator('.thumb').count(), 2);
  assert.match(await page.locator('#camera').textContent(), /sample camera/);
  assert.equal(await page.evaluate(() => typeof require), 'undefined');
  assert.equal(await page.evaluate(() => typeof window.fsc), 'object');
  await page.screenshot({ path: path.resolve('.qa', 'fsc-desktop.png') });
  await page.locator('#original').click();
  await page.waitForFunction(() => document.querySelector('#caption').textContent.includes('original'));
  await page.locator('#framed').click();
  await page.locator('#loading').waitFor({ state: 'hidden', timeout: 60000 });
  await page.locator('input[value=smart]').check();
  await page.locator('#loading').waitFor({ state: 'hidden', timeout: 60000 });
  await page.locator('.thumb').nth(1).click();
  await page.locator('#pages button').nth(3).waitFor({ state: 'visible', timeout: 60000 });
  assert.equal(await page.locator('#pages button').count(), 4);
  await page.locator('#pages button').first().click();
  assert.match(await page.locator('#caption').textContent(), /slice 1/);
  await page.screenshot({ path: path.resolve('.qa', 'fsc-panorama.png') });
  await page.locator('#export').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('done'), null, { timeout: 120000 });
  assert.match(await page.locator('#status').textContent(), /2 photos · 5 files exported/);
  assert.equal((await readdir(path.join(exportsDir,'matted'))).length,5);
  await page.locator('#export').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('done'), null, { timeout: 120000 });
  assert.equal((await readdir(path.join(exportsDir,'matted'))).length,10);
  await page.locator('#clear').click();
  await page.locator('#empty').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#export').isDisabled(), true);
  await page.screenshot({ path: path.resolve('.qa','fsc-empty.png') });
  // Mock only the OS picker result; exercise the app's actual buttons and IPC.
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled:false, filePaths:[file] }); }, photo);
  await page.locator('#add').click();
  await page.locator('.thumb').waitFor({ state:'visible' });
  await page.locator('#loading').waitFor({ state:'hidden', timeout:60000 });
  assert.equal(await page.locator('.thumb').count(),1);
  await page.locator('#remove').click();
  await page.locator('#empty').waitFor({ state:'visible' });
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled:false, filePaths:[folder] }); }, exportsDir);
  await page.locator('#folder').click();
  await page.waitForFunction(() => document.querySelectorAll('.thumb').length === 2);
  await page.locator('#loading').waitFor({ state:'hidden', timeout:60000 });
  const chosenOutput = path.join(root,'chosen-output'); await mkdir(chosenOutput);
  await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled:false, filePaths:[folder] }); }, chosenOutput);
  await page.locator('#output').click();
  await page.waitForFunction(() => document.querySelector('#output-path').textContent.includes('chosen-output'));
  await page.locator('#export').click();
  await page.waitForFunction(() => document.querySelector('#status').textContent.startsWith('done'), null, { timeout:120000 });
  assert.equal((await readdir(chosenOutput)).length,5);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok:true, checks:['app launch','metadata','renderer isolation','original/framed preview','smart panorama pages','five-file batch export','repeat export preserves files','clear queue','add/remove photo','add folder','choose output folder'], screenshot: path.resolve('.qa','fsc-desktop.png'), executablePath: executablePath || 'development' }, null, 2));
} finally { await app.close(); }
